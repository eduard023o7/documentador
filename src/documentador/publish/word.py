"""Markdown → Word with the corporate template → PDF (business rules BR-U0-27 to BR-U0-30).

Word is generated by Pandoc using the template as reference document (styles, headers and
footers). The PDF is always generated from the Word file with LibreOffice, so both look the same.
"""

from __future__ import annotations

import copy
import shutil
import subprocess
import tempfile
from collections.abc import Callable
from pathlib import Path

from docx import Document as WordDocument
from docx.oxml import parse_xml

from documentador.common.errors import DocumentadorError
from documentador.core.document import REFERENCE, Document, render_document
from documentador.core.profile_models import Profile

WATERMARK_TEXT = "BORRADOR"
APPROVED_STATE = "aprobado"
TIMEOUT_SECONDS = 120

# Same structure Word writes for a text watermark; LibreOffice recognizes the
# "PowerPlusWaterMarkObject" shape name and renders it as a watermark too.
_WATERMARK_XML = (
    '<w:p xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main" '
    'xmlns:v="urn:schemas-microsoft-com:vml" xmlns:o="urn:schemas-microsoft-com:office:office" '
    'xmlns:w10="urn:schemas-microsoft-com:office:word">'
    "<w:r><w:rPr><w:noProof/></w:rPr><w:pict>"
    '<v:shapetype id="_x0000_t136" coordsize="21600,21600" o:spt="136" adj="10800" '
    'path="m@7,l@8,m@5,21600l@6,21600e">'
    '<v:path textpathok="t" o:connecttype="custom"/>'
    '<v:textpath on="t" fitshape="t"/>'
    '<o:lock v:ext="edit" text="t" shapetype="t"/>'
    "</v:shapetype>"
    '<v:shape id="PowerPlusWaterMarkObject" o:spid="_x0000_s2049" type="#_x0000_t136" '
    'style="position:absolute;margin-left:0;margin-top:0;width:468pt;height:117pt;rotation:315;'
    "z-index:-251657216;mso-position-horizontal:center;mso-position-horizontal-relative:margin;"
    'mso-position-vertical:center;mso-position-vertical-relative:margin" '
    'o:allowincell="f" fillcolor="silver" stroked="f">'
    '<v:fill opacity=".5"/>'
    f'<v:textpath style="font-family:&quot;Calibri&quot;;font-size:1pt" string="{WATERMARK_TEXT}"/>'
    '<w10:wrap anchorx="margin" anchory="margin"/>'
    "</v:shape></w:pict></w:r></w:p>"
)


class ConversionError(DocumentadorError):
    """Pandoc or LibreOffice failed or is not installed."""


def link_references(markdown: str, link_for: Callable[[str], str]) -> str:
    """Turn every [[ID]] into a Markdown link [ID](url) (BR-U0-30)."""
    return REFERENCE.sub(lambda m: f"[{m['ref']}]({link_for(m['ref'])})", markdown)


def default_link(ref: str) -> str:
    """U0 link target: the document file in the repository (U3 points to the published version)."""
    doc_id = ref.split(".R")[0]
    anchor = f"#{ref.lower().replace('.', '')}" if ".R" in ref else ""
    return f"{doc_id}.md{anchor}"


def document_markdown(doc: Document, profile: Profile, link_for: Callable[[str], str] = default_link) -> str:
    """Markdown ready for conversion: title, a short ficha table and the body sections."""
    ficha = doc.ficha
    body = render_document(doc, profile).split("\n---\n", 1)[1].lstrip("\n")
    header = [
        f"# {ficha.id} · {ficha.titulo}",
        "",
        "| Tipo | Dominio | Versión | Estado |",
        "|---|---|---|---|",
        f"| {profile.doc_type(ficha.tipo).nombre} | {ficha.dominio} | {ficha.version} | {ficha.estado} |",
        "",
    ]
    return link_references("\n".join(header) + body, link_for)


def is_draft(doc: Document) -> bool:
    return doc.ficha.estado != APPROVED_STATE


def draft_template(template: Path, target: Path) -> Path:
    """Copy of the template with a "BORRADOR" watermark in every header (BR-U0-28)."""
    word = WordDocument(str(template))
    for section in word.sections:
        for header in (section.header, section.first_page_header, section.even_page_header):
            header.is_linked_to_previous = False
            header._element.append(copy.deepcopy(parse_xml(_WATERMARK_XML)))
    target.parent.mkdir(parents=True, exist_ok=True)
    word.save(str(target))
    return target


def render_docx(markdown: str, template: Path, draft: bool) -> bytes:
    """Word file using the template styles; drafts carry the watermark (BR-U0-27, BR-U0-28)."""
    _require("pandoc")
    with tempfile.TemporaryDirectory() as tmp:
        folder = Path(tmp)
        reference = draft_template(template, folder / "referencia.docx") if draft else template
        source = folder / "documento.md"
        source.write_text(markdown, encoding="utf-8")
        output = folder / "documento.docx"
        _run(
            [
                "pandoc",
                str(source),
                "-f",
                "markdown",
                "-t",
                "docx",
                "--reference-doc",
                str(reference),
                "-o",
                str(output),
            ],
            "Pandoc no pudo generar el Word",
        )
        return output.read_bytes()


def render_pdf(docx: bytes) -> bytes:
    """PDF from the Word file, never directly from Markdown (BR-U0-29)."""
    office = _office_binary()
    with tempfile.TemporaryDirectory() as tmp:
        folder = Path(tmp)
        source = folder / "documento.docx"
        source.write_bytes(docx)
        _run(
            [
                office,
                "--headless",
                f"-env:UserInstallation=file://{folder}/perfil",
                "--convert-to",
                "pdf",
                "--outdir",
                str(folder),
                str(source),
            ],
            "LibreOffice no pudo generar el PDF",
        )
        pdf = folder / "documento.pdf"
        if not pdf.exists():
            raise ConversionError("LibreOffice no generó el PDF.")
        return pdf.read_bytes()


def _office_binary() -> str:
    for name in ("soffice", "libreoffice"):
        if shutil.which(name):
            return name
    raise ConversionError("No se encontró LibreOffice.", "Instálalo para generar PDF (paquete libreoffice).")


def _require(binary: str) -> None:
    if not shutil.which(binary):
        raise ConversionError(f"No se encontró {binary}.", f"Instala {binary} para generar Word.")


def _run(command: list[str], failure: str) -> None:
    try:
        subprocess.run(command, check=True, capture_output=True, timeout=TIMEOUT_SECONDS)
    except subprocess.CalledProcessError as exc:
        detail = exc.stderr.decode("utf-8", "replace")[-500:]
        raise ConversionError(f"{failure}: {detail}") from exc
    except subprocess.TimeoutExpired as exc:
        raise ConversionError(f"{failure}: se superaron {TIMEOUT_SECONDS} s.") from exc
